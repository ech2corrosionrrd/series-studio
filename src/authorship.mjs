/**
 * Human contribution record for an export. Two parts:
 *   declared: what the author says (where the base image came from, hand edits, hand-drawn layers, a note);
 *   facts:    what the studio can count from the set (frames kept by hand, regenerated, marked redo).
 * Goes into the ZIP as authorship.json and a block in README.txt.
 * It is the author's statement and a log of actions, not legal advice. The U.S. Copyright Office
 * (29.01.2025) protects human selection, arrangement and modification, not a prompt on its own.
 */
import { readMeta } from "./versions.mjs";

export const BASE_ORIGINS = ["hand", "photo", "ai_curated", "ai_raw"];

const text = (v, max) => String(v ?? "").trim().slice(0, max);

/** Clean the form values. Unknown origin becomes "" (not declared). */
export function normalizeAuthorship(raw) {
  if (!raw || typeof raw !== "object") return null;
  const baseOrigin = BASE_ORIGINS.includes(raw.baseOrigin) ? raw.baseOrigin : "";
  const out = {
    baseOrigin,
    handEdited: raw.handEdited === true,
    handLayers: raw.handLayers === true,
    note: text(raw.note, 1000),
  };
  return out.baseOrigin || out.handEdited || out.handLayers || out.note ? out : null;
}

/**
 * @param {{ setDir: string, editions: number[], marks?: Record<string,string> }} args
 */
export function authorshipFacts({ setDir, editions, marks = {} }) {
  let keptByHand = 0;
  let regenerated = 0;
  let versions = 0;
  for (const ed of editions) {
    if ((marks[String(ed)] ?? marks[ed]) === "keep") keptByHand++;
    try {
      const n = readMeta(setDir, ed).versions.length;
      versions += n;
      if (n > 1) regenerated++;
    } catch {
      /* a frame without history counts as one version */
      versions += 1;
    }
  }
  const redoMarked = Object.values(marks || {}).filter((v) => v === "redo").length;
  return { frames: editions.length, keptByHand, redoMarked, regenerated, versions };
}

export function authorshipDoc({ declared, facts }) {
  return {
    schema: "series-authorship/v0",
    declared: declared || null,
    facts,
    note: "Author's statement and a log of studio actions. Not legal advice.",
  };
}

const ORIGIN = {
  uk: {
    hand: "намальована автором вручну",
    photo: "фото або колаж автора",
    ai_curated: "згенерована ШІ, відібрана й доопрацьована автором",
    ai_raw: "згенерована ШІ без правок",
  },
  en: {
    hand: "drawn by the author by hand",
    photo: "the author's photo or collage",
    ai_curated: "generated by AI, selected and refined by the author",
    ai_raw: "generated by AI, unedited",
  },
};

/** Text block for README.txt. Empty string when there is nothing to say. */
export function authorshipText(locale, doc) {
  if (!doc) return "";
  const uk = String(locale || "").toLowerCase().startsWith("uk");
  const d = doc.declared;
  const f = doc.facts;
  const yes = uk ? "так" : "yes";
  const lines = uk
    ? ["----- ЛЮДСЬКИЙ ВНЕСОК (заява автора, не юридичний висновок) -----"]
    : ["----- HUMAN CONTRIBUTION (the author's statement, not legal advice) -----"];
  if (d) {
    if (d.baseOrigin) lines.push(`${uk ? "Базова картинка" : "Base image"}: ${ORIGIN[uk ? "uk" : "en"][d.baseOrigin]}`);
    if (d.handEdited) lines.push(`${uk ? "Автор вручну правив або дорисовував кадри" : "The author edited or painted over frames by hand"}: ${yes}`);
    if (d.handLayers) lines.push(`${uk ? "Риси намальовано вручну (шари)" : "Traits drawn by hand (layers)"}: ${yes}`);
    if (d.note) lines.push(`${uk ? "Примітка автора" : "Author's note"}: ${d.note}`);
  }
  lines.push(
    uk
      ? `Із журналу студії: у наборі ${f.frames} кадрів, ${f.keptByHand} з них автор позначив «Лишити» вручну, ${f.regenerated} перегенеровано (кілька версій), версій усього ${f.versions}.`
      : `From the studio log: ${f.frames} frames in the set, ${f.keptByHand} marked Keep by the author, ${f.regenerated} regenerated (several versions), ${f.versions} versions in total.`,
  );
  lines.push(uk ? "----- КІНЕЦЬ -----" : "----- END -----");
  return lines.join("\n");
}
